"""make sim: every scenario x mode x provider, CSVs to results/sim/, charts to docs/img/,
summary table to docs/SIMULATION_RESULTS.md (the numbers section is regenerated; the
interpretation section is kept as written)."""
import csv
import json
from pathlib import Path

from sim.charts import run_figure
from sim.scenarios import SCENARIOS
from sim.simulator import Sim

ROOT = Path(__file__).resolve().parent.parent
CSV_DIR, IMG_DIR, DOC = ROOT / "results" / "sim", ROOT / "docs" / "img", ROOT / "docs" / "SIMULATION_RESULTS.md"
SEED = 7
MARK = "<!-- generated-below -->"


def rows_of(sim: Sim) -> list[dict]:
    out = []
    for i, b in enumerate(sim.buckets[: int(sim.sc.duration_s // 60)]):
        out.append({"minute": i, "dials": b.dials, "answered": b.answered, "connected": b.connected,
                    "abandoned": b.abandoned, "utilization": b.talk_s / (sim.sc.agents * 60),
                    "pacing_ratio": b.ratio_sum / b.ticks if b.ticks else 0.0,
                    "avg_approved_per_tick": b.approved / b.ticks if b.ticks else 0.0,
                    "predictive_share": b.predictive_ticks / b.ticks if b.ticks else 0.0,
                    "reasons": dict(b.reasons), "outcomes": dict(b.outcomes)})
    return out


def write_csv(path: Path, rows: list[dict]):
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        for r in rows:
            w.writerow({**r, "reasons": json.dumps(r["reasons"]), "outcomes": json.dumps(r["outcomes"])})


def run(scenario: str, provider: str) -> dict:
    sc = SCENARIOS[scenario]
    runs, summaries = {}, {}
    for mode in ("PROGRESSIVE", "PREDICTIVE"):
        sim = Sim(sc, mode, provider, seed=SEED).run()
        runs[mode] = rows_of(sim)
        summaries[mode] = sim.summary()
        write_csv(CSV_DIR / f"{scenario}_{mode.lower()}_{provider}.csv", runs[mode])
    img = IMG_DIR / f"sim_{scenario}_{provider}.png"
    run_figure(img, f"Scenario {scenario}: {sc.description} | Provider {provider} | {sc.agents} agents",
               runs, shock_min=sc.shock_at_s / 60 if sc.shock_at_s else None)
    return summaries


def main():
    CSV_DIR.mkdir(parents=True, exist_ok=True)
    IMG_DIR.mkdir(parents=True, exist_ok=True)
    lines = ["| Scenario | Provider | Mode | Utilization | Connects / agent-hour | Abandon rate | Abandoned / answered | Ticks in predictive mode |",
             "|---|---|---|---|---|---|---|---|"]
    for scenario in ("A", "B", "C", "D", "E", "F"):
        for provider in (("A", "B") if scenario in "ABCD" else ("A",)):
            s = run(scenario, provider)
            for mode in ("PROGRESSIVE", "PREDICTIVE"):
                m = s[mode]
                lines.append(f"| {scenario} | {provider} | {mode.lower()} | {m['utilization']:.1%} | {m['connects_per_agent_hour']:.1f}"
                             f" | {m['abandon_rate']:.2%} | {m['abandoned']} / {m['answered']} | {m['predictive_share']:.0%} |")
            gain = s["PREDICTIVE"]["utilization"] / s["PROGRESSIVE"]["utilization"] - 1 if s["PROGRESSIVE"]["utilization"] else 0
            print(f"scenario {scenario} provider {provider}: predictive utilization {gain:+.0%} vs progressive")
    table = "\n".join(lines)
    charts = "\n".join(f"- [Scenario {s}, Provider {p}](img/sim_{s}_{p}.png)"
                       for s in "ABCDEF" for p in (("A", "B") if s in "ABCD" else ("A",)))
    generated = (f"{MARK}\n\n## Results (generated by `make sim`, seed {SEED}, first 5 minutes excluded as warm-up)\n\n"
                 f"{table}\n\n### Charts\n\n{charts}\n\nPer-minute CSVs: `results/sim/<scenario>_<mode>_<provider>.csv`.\n")
    head = DOC.read_text().split(MARK)[0] if DOC.exists() else "# Simulation results\n\n"
    DOC.write_text(head + generated)
    print(f"wrote {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
