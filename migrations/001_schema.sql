-- SmartDialer schema. PostgreSQL is the single source of truth; there is no cache.
-- All time comparisons use the DB clock (now() / clock_timestamp()), never a worker clock.

CREATE TABLE campaigns (
    id                      bigserial PRIMARY KEY,
    name                    text NOT NULL,
    mode                    text NOT NULL CHECK (mode IN ('PROGRESSIVE', 'PREDICTIVE')),
    provider_name           text NOT NULL DEFAULT 'A',
    timezone                text NOT NULL DEFAULT 'Asia/Kolkata',
    settings                jsonb NOT NULL DEFAULT '{}',
    -- Pacing leadership: one worker paces a campaign at a time. fencing_token is bumped on
    -- every takeover; permits carry it, so permits from a deposed leader stop working.
    pacing_lease_owner      text,
    pacing_lease_expires_at timestamptz,
    fencing_token           bigint NOT NULL DEFAULT 0,
    -- Safety Controller memory between ticks (hysteresis and cooldowns), see safety_rules.py.
    safety_state            jsonb NOT NULL DEFAULT '{}'
);

CREATE TABLE workers (
    id                text PRIMARY KEY,
    started_at        timestamptz NOT NULL DEFAULT now(),
    last_heartbeat_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE agents (
    id                 bigserial PRIMARY KEY,
    campaign_id        bigint NOT NULL REFERENCES campaigns(id),
    name               text NOT NULL,
    state              text NOT NULL DEFAULT 'OFFLINE'
                       CHECK (state IN ('OFFLINE','AVAILABLE','RESERVED','DIALING','CONNECTED','WRAP_UP','PAUSED')),
    -- Fencing token for every worker-driven transition after reservation. Call ids are never
    -- reused, so a stale worker holding an old call id can never match (no ABA problem).
    reserved_call_id   uuid,
    reserved_by_worker text,
    last_heartbeat_at  timestamptz NOT NULL DEFAULT now(),   -- the human agent's client presence
    state_changed_at   timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX agents_pick ON agents (campaign_id, state, state_changed_at);

CREATE TABLE agent_transitions (
    id         bigserial PRIMARY KEY,
    agent_id   bigint NOT NULL REFERENCES agents(id),
    from_state text NOT NULL,
    to_state   text NOT NULL,
    call_id    uuid,
    worker_id  text,
    reason     text,
    at         timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX agent_transitions_agent ON agent_transitions (agent_id, at);

CREATE TABLE borrowers (
    id               bigserial PRIMARY KEY,
    campaign_id      bigint NOT NULL REFERENCES campaigns(id),
    phone            text NOT NULL,
    state            text NOT NULL DEFAULT 'PENDING'
                     CHECK (state IN ('PENDING','IN_PROGRESS','DONE','EXHAUSTED')),
    attempts         int NOT NULL DEFAULT 0,
    next_attempt_at  timestamptz NOT NULL DEFAULT now(),
    locked_by_worker text,
    last_outcome     text,
    updated_at       timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX borrowers_ready ON borrowers (campaign_id, next_attempt_at, id) WHERE state = 'PENDING';

CREATE TABLE dial_permits (
    id             bigserial PRIMARY KEY,
    campaign_id    bigint NOT NULL REFERENCES campaigns(id),
    fencing_token  bigint NOT NULL,
    mode           text NOT NULL CHECK (mode IN ('PROGRESSIVE', 'PREDICTIVE')),
    approved_count int NOT NULL CHECK (approved_count >= 0),
    consumed_count int NOT NULL DEFAULT 0,
    expires_at     timestamptz NOT NULL,
    revoked        boolean NOT NULL DEFAULT false,
    decision_id    bigint,
    created_at     timestamptz NOT NULL DEFAULT clock_timestamp(),
    -- Backstop: even a buggy consume statement cannot over-consume a permit.
    CONSTRAINT permit_not_overconsumed CHECK (consumed_count <= approved_count)
);
-- Backstop: at most one live permit per campaign, so unconsumed permits cannot stack up.
CREATE UNIQUE INDEX one_active_permit ON dial_permits (campaign_id) WHERE NOT revoked;

CREATE TABLE calls (
    -- Generated by us before contacting the provider, and sent as the provider idempotency key.
    id                uuid PRIMARY KEY,
    campaign_id       bigint NOT NULL REFERENCES campaigns(id),
    borrower_id       bigint NOT NULL REFERENCES borrowers(id),
    agent_id          bigint REFERENCES agents(id),   -- predictive calls get an agent only on answer
    mode              text NOT NULL CHECK (mode IN ('PROGRESSIVE', 'PREDICTIVE')),
    state             text NOT NULL,
    state_rank        smallint NOT NULL,
    provider_name     text NOT NULL,
    provider_call_id  text,
    failure_reason    text,
    owner_worker      text,                           -- who dialed it (for humans; not used for correctness)
    permit_id         bigint REFERENCES dial_permits(id),
    created_at        timestamptz NOT NULL DEFAULT clock_timestamp(),
    state_changed_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    dialed_at         timestamptz,
    answered_at       timestamptz,
    connected_at      timestamptz,
    ended_at          timestamptz,
    duration_s        double precision,
    answered_inferred boolean NOT NULL DEFAULT false,
    reconcile_attempts int NOT NULL DEFAULT 0,
    UNIQUE (provider_name, provider_call_id)
);
CREATE INDEX calls_live ON calls (campaign_id, state)
    WHERE state NOT IN ('COMPLETED','FAILED','CANCELLED','ABANDONED');
CREATE INDEX calls_recent ON calls (campaign_id, ended_at);
-- Backstops: the allocator should never get here, and a violation is a bug, not a retry.
CREATE UNIQUE INDEX one_live_call_per_borrower ON calls (borrower_id)
    WHERE state NOT IN ('COMPLETED','FAILED','CANCELLED','ABANDONED');
CREATE UNIQUE INDEX one_live_call_per_agent ON calls (agent_id)
    WHERE agent_id IS NOT NULL AND state NOT IN ('COMPLETED','FAILED','CANCELLED','ABANDONED');

CREATE TABLE call_transitions (
    id             bigserial PRIMARY KEY,
    call_id        uuid NOT NULL REFERENCES calls(id),
    from_state     text,
    to_state       text NOT NULL,
    cause_event_id bigint,
    worker_id      text,
    at             timestamptz NOT NULL DEFAULT clock_timestamp(),
    -- Ranks only move forward, so a call enters each state at most once. A duplicate
    -- transition is not just avoided by code, it cannot be written.
    UNIQUE (call_id, to_state)
);

CREATE TABLE provider_events (
    id                 bigserial PRIMARY KEY,
    provider_name      text NOT NULL,
    provider_event_id  text NOT NULL,
    call_id            uuid,            -- our idempotency key, echoed back by the provider
    provider_call_id   text,
    event_type         text NOT NULL,
    sequence           int,
    provider_timestamp timestamptz,
    payload            jsonb NOT NULL DEFAULT '{}',
    received_at        timestamptz NOT NULL DEFAULT clock_timestamp(),
    attempts           int NOT NULL DEFAULT 0,
    next_attempt_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
    processed_at       timestamptz,
    processing_result  text CHECK (processing_result IN ('APPLIED','DUPLICATE','STALE_IGNORED','REJECTED','ORPHAN')),
    -- First duplicate barrier: an exact redelivery is dropped at insert.
    UNIQUE (provider_name, provider_event_id)
);
CREATE INDEX provider_events_pending ON provider_events (next_attempt_at, id) WHERE processed_at IS NULL;

CREATE TABLE safety_decisions (
    id             bigserial PRIMARY KEY,
    campaign_id    bigint NOT NULL REFERENCES campaigns(id),
    at             timestamptz NOT NULL DEFAULT clock_timestamp(),
    worker_id      text,
    fencing_token  bigint,
    requested      int NOT NULL,
    proposal_mode  text NOT NULL,
    explanation    text NOT NULL,
    snapshot       jsonb NOT NULL,
    approved_count int NOT NULL,
    outcome        text NOT NULL CHECK (outcome IN ('APPROVE','REDUCE','REJECT','FALLBACK_TO_PROGRESSIVE')),
    mode           text NOT NULL,
    reason_codes   text[] NOT NULL DEFAULT '{}'
);
CREATE INDEX safety_decisions_campaign ON safety_decisions (campaign_id, at);

CREATE TABLE provider_health (
    provider_name    text PRIMARY KEY,
    breaker_state    text NOT NULL DEFAULT 'CLOSED' CHECK (breaker_state IN ('CLOSED','OPEN','HALF_OPEN')),
    opened_at        timestamptz,
    updated_at       timestamptz NOT NULL DEFAULT now()
);
